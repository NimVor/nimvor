package pgmgr

import (
	"context"
	"strings"
	"testing"

	"github.com/NimVor/nimvor/agent/internal/actions"
	"github.com/NimVor/nimvor/agent/internal/testhost"
)

func TestStructureChanges(t *testing.T) {
	c := startCluster(t)
	h := testhost.New(t)
	c.admin(t, h.Env)
	r := actions.NewRegistry(true)
	Register(r, h.Env)
	ctx := context.Background()
	mustCall(t, r, "pg.role_create", map[string]any{"name": "owner_d", "password": pwA})
	mustCall(t, r, "pg.database_create", map[string]any{"name": "db_d", "owner": "owner_d"})
	a, err := c.as("owner_d", pwA, "db_d")
	if err != nil {
		t.Fatal(err)
	}
	defer a.Close(ctx)
	if _, err := a.Exec(ctx, `CREATE SCHEMA app`); err != nil {
		t.Fatal(err)
	}
	alter := func(p map[string]any) (map[string]any, error) {
		p["database"] = "db_d"
		out, err := call(t, r, "pg.table_alter", p)
		if err != nil {
			return nil, err
		}
		return asMap(t, out), nil
	}
	must := func(p map[string]any) map[string]any {
		t.Helper()
		out, err := alter(p)
		if err != nil {
			t.Fatalf("%v: %v", p, err)
		}
		return out
	}
	cols := []any{
		map[string]any{"name": "id", "type": "integer", "identity": true, "primary": true, "not_null": true},
		map[string]any{"name": "title", "type": "VARCHAR(80)", "not_null": true, "has_default": true, "default": "it's \\ fine"},
		map[string]any{"name": "created", "type": "timestamptz", "has_default": true, "default": "now", "default_fn": true},
		map[string]any{"name": "tags", "type": "text[]"},
	}

	// Dry run shows the SQL and changes nothing.
	dry := must(map[string]any{"op": "create_table", "schema": "public", "table": "posts", "columns": cols, "dry_run": true})
	sql := dry["sql"].(string)
	for _, want := range []string{`CREATE TABLE "public"."posts"`, `"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL`, `DEFAULT E'it''s \\ fine'`, `DEFAULT now()`, `"tags" text[]`, `PRIMARY KEY ("id")`} {
		if !strings.Contains(sql, want) {
			t.Errorf("create SQL lacks %s:\n%s", want, sql)
		}
	}
	var n int
	if err := a.QueryRow(ctx, `SELECT count(*) FROM pg_tables WHERE tablename = 'posts'`).Scan(&n); err != nil || n != 0 {
		t.Fatalf("dry run created the table (%d, %v)", n, err)
	}
	must(map[string]any{"op": "create_table", "schema": "public", "table": "posts", "columns": cols})
	if _, err := a.Exec(ctx, `INSERT INTO posts (title) VALUES ('first'), ('second')`); err != nil {
		t.Fatalf("created table does not work: %v", err)
	}

	// Refused input.
	for name, p := range map[string]map[string]any{
		"unknown type":        {"op": "create_table", "schema": "public", "table": "x", "columns": []any{map[string]any{"name": "a", "type": "integer); DROP TABLE posts; --"}}},
		"function default":    {"op": "create_table", "schema": "public", "table": "x", "columns": []any{map[string]any{"name": "a", "type": "text", "has_default": true, "default": "pg_sleep(100)", "default_fn": true}}},
		"duplicate column":    {"op": "create_table", "schema": "public", "table": "x", "columns": []any{map[string]any{"name": "a", "type": "text"}, map[string]any{"name": "a", "type": "text"}}},
		"no columns":          {"op": "create_table", "schema": "public", "table": "x", "columns": []any{}},
		"unknown op":          {"op": "drop_database", "schema": "public", "table": "posts"},
		"system table":        {"op": "rename_table", "schema": "pg_catalog", "table": "pg_class", "new_name": "x"},
		"serial array":        {"op": "add_column", "schema": "public", "table": "posts", "column": map[string]any{"name": "s", "type": "serial[]"}},
		"identity on text":    {"op": "add_column", "schema": "public", "table": "posts", "column": map[string]any{"name": "s", "type": "text", "identity": true}},
		"existing column":     {"op": "add_column", "schema": "public", "table": "posts", "column": map[string]any{"name": "title", "type": "text"}},
		"unknown schema":      {"op": "set_schema", "schema": "public", "table": "posts", "new_schema": "nowhere"},
		"system schema":       {"op": "set_schema", "schema": "public", "table": "posts", "new_schema": "pg_catalog"},
		"drop only column":    {"op": "drop_column", "schema": "public", "table": "tags_only", "name": "x"},
		"missing column":      {"op": "rename_column", "schema": "public", "table": "posts", "name": "nope", "new_name": "x"},
		"bad alter_what":      {"op": "alter_column", "schema": "public", "table": "posts", "name": "title", "extra": map[string]any{"alter_what": "owner"}},
		"type with injection": {"op": "alter_column", "schema": "public", "table": "posts", "name": "title", "extra": map[string]any{"alter_what": "type", "value": "text; DROP TABLE posts"}},
	} {
		if _, err := alter(p); err == nil {
			t.Errorf("%s: must be refused", name)
		}
	}
	if err := a.QueryRow(ctx, `SELECT count(*) FROM posts`).Scan(&n); err != nil || n != 2 {
		t.Fatalf("a refused request changed data: %d %v", n, err)
	}

	// Columns.
	must(map[string]any{"op": "add_column", "schema": "public", "table": "posts", "column": map[string]any{"name": "views", "type": "bigint", "not_null": true, "has_default": true, "default": "0"}})
	must(map[string]any{"op": "alter_column", "schema": "public", "table": "posts", "name": "views", "extra": map[string]any{"alter_what": "type", "value": "numeric(12,2)"}})
	must(map[string]any{"op": "alter_column", "schema": "public", "table": "posts", "name": "views", "extra": map[string]any{"alter_what": "drop_not_null"}})
	must(map[string]any{"op": "alter_column", "schema": "public", "table": "posts", "name": "views", "extra": map[string]any{"alter_what": "set_default", "value": "5"}})
	must(map[string]any{"op": "alter_column", "schema": "public", "table": "posts", "name": "views", "extra": map[string]any{"alter_what": "comment", "value": "page views"}})
	must(map[string]any{"op": "rename_column", "schema": "public", "table": "posts", "name": "views", "new_name": "hits"})
	var typ, cmt string
	if err := a.QueryRow(ctx, `SELECT format_type(atttypid, atttypmod), col_description(attrelid, attnum) FROM pg_attribute WHERE attrelid = 'public.posts'::regclass AND attname = 'hits'`).Scan(&typ, &cmt); err != nil || typ != "numeric(12,2)" || cmt != "page views" {
		t.Errorf("column after changes: %q %q %v", typ, cmt, err)
	}
	if _, err := alter(map[string]any{"op": "alter_column", "schema": "public", "table": "posts", "name": "title", "extra": map[string]any{"alter_what": "type", "value": "integer"}}); err == nil {
		t.Error("converting text to integer must fail (values do not convert) and say so")
	}
	must(map[string]any{"op": "drop_column", "schema": "public", "table": "posts", "name": "tags"})

	// Table level: comment, duplicate with data, rename, move to another schema.
	must(map[string]any{"op": "comment_table", "schema": "public", "table": "posts", "comment": "blog; posts"})
	must(map[string]any{"op": "duplicate_table", "schema": "public", "table": "posts", "new_name": "posts_copy", "with_data": true})
	if err := a.QueryRow(ctx, `SELECT count(*) FROM posts_copy`).Scan(&n); err != nil || n != 2 {
		t.Errorf("copy has %d rows (%v)", n, err)
	}
	if _, err := alter(map[string]any{"op": "duplicate_table", "schema": "public", "table": "posts", "new_name": "posts_copy"}); err == nil {
		t.Error("duplicating onto an existing name must fail")
	}
	must(map[string]any{"op": "rename_table", "schema": "public", "table": "posts_copy", "new_name": "archive"})
	must(map[string]any{"op": "set_schema", "schema": "public", "table": "archive", "new_schema": "app"})
	if err := a.QueryRow(ctx, `SELECT count(*) FROM app.archive`).Scan(&n); err != nil || n != 2 {
		t.Errorf("moved table: %d %v", n, err)
	}
}
