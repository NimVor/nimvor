            '10000010101010111100001001011110011001110',
            '00101101100010110010001000110011100111010',
            '00001110011101100010111001110000011111110',
            '10100100011111011011001000101011010111010',
            '11010110010110100101010001011010001100011',
            '01011001000010101100000110111101101110001',
