    public function testVersionSelectionAndLimits(): void
    {
        self::assertSame(1, QrCode::encode(str_repeat('a', 14))->version);
        self::assertSame(2, QrCode::encode(str_repeat('a', 15))->version);
        self::assertSame(15, QrCode::encode(str_repeat('a', 412))->version);
        $this->expectException(\InvalidArgumentException::class);
        QrCode::encode(str_repeat('a', 413));
    }

    public function testSvgIsSelfContained(): void
    {
        $svg = QrCode::encode('hello')->svg(4, 'a "label"');
        self::assertStringStartsWith('<svg xmlns="http://www.w3.org/2000/svg"', $svg);
        self::assertStringContainsString('aria-label="a &quot;label&quot;"', $svg);
        self::assertStringNotContainsString('style=', $svg, 'no inline styles (CSP)');
        self::assertStringNotContainsString('<script', $svg);
    }
