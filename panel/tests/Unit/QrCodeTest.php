<?php

declare(strict_types=1);

namespace WhaCP\Tests\Unit;

use PHPUnit\Framework\TestCase;
use WhaCP\Security\QrCode;

/**
 * Fixtures were produced by an independent encoder (python-qrcode, level M,
 * byte mode, same mask) and must match module for module.
 */
final class QrCodeTest extends TestCase
{
    private static function rows(QrCode $q): array
    {
        $out = [];
        for ($y = 0; $y < $q->size(); $y++) {
            $r = '';
            for ($x = 0; $x < $q->size(); $x++) {
                $r .= $q->dark($y, $x) ? '1' : '0';
            }
            $out[] = $r;
        }
        return $out;
    }

    public function testMatchesReferenceVersion1(): void
    {
        $q = QrCode::encode('WhaCP', 3);
        self::assertSame(1, $q->version);
        self::assertSame([
            '111111101110001111111',
            '100000101001101000001',
            '101110100001101011101',
            '101110101011101011101',
            '101110100011001011101',
            '100000100111101000001',
            '111111101010101111111',
            '000000001011100000000',
            '101101110111101001011',
            '010001001101111000001',
            '000101101101000001011',
            '011101000001001111001',
            '000101111110100100010',
            '000000001011001001011',
            '111111101001100101000',
            '100000101010000111110',
            '101110100010111111011',
            '101110101111001010010',
            '101110101000101101000',
            '100000100100010000001',
            '111111101100010011000',
        ], self::rows($q));
    }

    public function testMatchesReferenceOtpauthUri(): void
