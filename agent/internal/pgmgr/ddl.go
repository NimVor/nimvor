// Structured schema changes for the PostgreSQL browser (pg.table_alter). The request is data, never SQL: every
// identifier is quoted with pgx.Identifier, a column type must match a fixed grammar of built-in types, a default is
// a literal (always quoted) or one of a few functions, and the operation is chosen from a fixed list. The statement
// runs as the database's owner through its query account (PostgreSQL's own privilege checks apply), and dry_run
// returns the SQL without running it so the panel can show exactly what would happen.

var (
	baseTypeRe   = regexp.MustCompile(`^(smallint|integer|int|int2|int4|int8|bigint|smallserial|serial|bigserial|text|boolean|bool|real|float4|float8|double precision|date|json|jsonb|uuid|bytea|inet|cidr|macaddr|money|interval|xml)$`)
	sizedTypeRe  = regexp.MustCompile(`^(varchar|character varying|char|character|bpchar)(\([1-9][0-9]{0,4}\))?$`)
	numericRe    = regexp.MustCompile(`^(numeric|decimal)(\([1-9][0-9]{0,2}(,[0-9]{1,3})?\))?$`)
	timeTypeRe   = regexp.MustCompile(`^(timestamp|timestamptz|time|timetz)(\([0-6]\))?( with(out)? time zone)?$`)
	defaultFuncs = map[string]string{"now": "now()", "current_timestamp": "CURRENT_TIMESTAMP", "current_date": "CURRENT_DATE", "gen_random_uuid": "gen_random_uuid()"}
)

// ColumnSpec describes a column to create or change.
type ColumnSpec struct {
	Name       string `json:"name"`
	Type       string `json:"type"`
	NotNull    bool   `json:"not_null"`
	Default    string `json:"default"`     // the text of a literal, or the name of one of the allowed functions when DefaultFn is set
	DefaultFn  bool   `json:"default_fn"`  // Default names a function (now, current_timestamp, current_date, gen_random_uuid)
	HasDefault bool   `json:"has_default"` // false: no default
	Identity   bool   `json:"identity"`    // GENERATED BY DEFAULT AS IDENTITY (integer types)
	Primary    bool   `json:"primary"`     // part of the primary key (create_table only)
	Comment    string `json:"comment"`
}

// checkType accepts a built-in type, optionally sized or an array of one; it returns the canonical text.
func checkType(t string) (string, error) {
	n := strings.ToLower(strings.Join(strings.Fields(t), " "))
	array := ""
	for strings.HasSuffix(n, "[]") && len(array) < 6 {
		n = strings.TrimSpace(strings.TrimSuffix(n, "[]"))
		array += "[]"
	}
	if baseTypeRe.MatchString(n) || sizedTypeRe.MatchString(n) || numericRe.MatchString(n) || timeTypeRe.MatchString(n) {
		if array != "" && strings.HasSuffix(n, "serial") {
			return "", errors.New("a serial column cannot be an array")
		}
		return n + array, nil
	}
	return "", fmt.Errorf("the type %q is not one NimVor offers; use the SQL tab for other types", t)
}

// quoteLiteral writes s as an SQL string literal. NUL cannot be represented and is refused.
func quoteLiteral(s string) (string, error) {
	if strings.ContainsRune(s, 0) {
		return "", errors.New("a value cannot contain a NUL character")
	}
	if strings.ContainsRune(s, '\\') {
		return "E'" + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), "'", "''") + "'", nil
	}
	return "'" + strings.ReplaceAll(s, "'", "''") + "'", nil
}

func checkName(what, n string) error {
	if n == "" || len(n) > 63 || strings.ContainsRune(n, 0) || !isValidUTF8(n) {
		return fmt.Errorf("%s: enter a name of 1 to 63 characters", what)
	}
	return nil
}

func isValidUTF8(s string) bool { return strings.ToValidUTF8(s, "�") == s }

// def renders a column definition (without the name): type, identity, default, NOT NULL.
func (c ColumnSpec) def(version int) (string, error) {
	t, err := checkType(c.Type)
	if err != nil {
		return "", err
	}
	out := t
	if c.Identity {
		if version < 100000 {
			return "", errors.New("identity columns need PostgreSQL 10 or newer; choose serial instead")
		}
		if t != "smallint" && t != "integer" && t != "int" && t != "bigint" && t != "int2" && t != "int4" && t != "int8" {
			return "", errors.New("an identity column must be an integer type")
		}
		out += " GENERATED BY DEFAULT AS IDENTITY"
	} else if c.HasDefault {
		d, err := c.defaultSQL()
		if err != nil {
			return "", err
		}
		out += " DEFAULT " + d
	}
	if c.NotNull {
		out += " NOT NULL"
	}
	return out, nil
}

func (c ColumnSpec) defaultSQL() (string, error) {
	if c.DefaultFn {
		f, ok := defaultFuncs[strings.ToLower(c.Default)]
		if !ok {
			return "", fmt.Errorf("default: the function %q is not offered (now, current_timestamp, current_date, gen_random_uuid)", c.Default)
		}
		return f, nil
	}
	return quoteLiteral(c.Default)
}

// AlterIn is the request of pg.table_alter.
type AlterIn struct {
	tableIn
	Op         string       `json:"op"`
	NewName    string       `json:"new_name"`
	NewSchema  string       `json:"new_schema"`
	Comment    string       `json:"comment"`
	Columns    []ColumnSpec `json:"columns"`   // create_table
	Column     *ColumnSpec  `json:"column"`    // add_column / alter_column
	Name       string       `json:"name"`      // column, index or constraint the operation names
	WithData   bool         `json:"with_data"` // duplicate_table
	DryRun     bool         `json:"dry_run"`
	Cascade    bool         `json:"cascade"`
	IfNotExist bool         `json:"if_not_exists"`
	Extra      alterExtra   `json:"extra"`
}

// alterExtra holds the operation-specific inputs added by later slices (indexes, constraints, sequences, partitions).
type alterExtra struct {
	Method     string     `json:"method"` // index access method
	Unique     bool       `json:"unique"`
	Concurrent bool       `json:"concurrent"`
	IndexCols  []IndexCol `json:"index_columns"`
	Include    []string   `json:"include"`
	Predicate  *Predicate `json:"predicate"` // partial index / CHECK condition: column, operator, value
	Columns    []string   `json:"columns"`   // constraint columns
	Bound      BoundIn    `json:"bound"`     // partition bound
	Kind       string     `json:"kind"`      // constraint kind: unique | check | foreign | primary
	RefSchema  string     `json:"ref_schema"`
	RefTable   string     `json:"ref_table"`
	RefColumns []string   `json:"ref_columns"`
	OnDelete   string     `json:"on_delete"`
	OnUpdate   string     `json:"on_update"`
	NotValid   bool       `json:"not_valid"`
	Deferrable bool       `json:"deferrable"`
	AlterWhat  string     `json:"alter_what"` // alter_column: type | not_null | default | comment | rename
	Value      string     `json:"value"`
}

// stmtSep separates the statements of an operation that needs more than one (a NUL cannot occur in any quoted
// identifier or literal here, so splitting on it is safe).
const stmtSep = "\x00"

func qident(parts ...string) string { return pgx.Identifier(parts).Sanitize() }

// alterSQL turns the request into one statement.
func (s *session) alterSQL(ctx context.Context, in AlterIn) (string, error) {
	switch in.Op {
	case "create_table":
		if err := checkName("schema", in.Schema); err != nil {
			return "", host.Invalid(err)
		}
		if err := checkName("table", in.Table); err != nil {
			return "", host.Invalid(err)
		}
		if len(in.Columns) == 0 || len(in.Columns) > 200 {
			return "", actions.InvalidParams("columns: a table needs between 1 and 200 columns.")
		}
		var defs, pk []string
		seen := map[string]bool{}
		for _, c := range in.Columns {
			if err := checkName("column", c.Name); err != nil {
				return "", host.Invalid(err)
			}
			if seen[c.Name] {
				return "", actions.InvalidParams("columns: " + c.Name + " appears twice.")
			}
			seen[c.Name] = true
			d, err := c.def(s.version)
			if err != nil {
				return "", actions.InvalidParams("column " + c.Name + ": " + err.Error())
			}
			defs = append(defs, qident(c.Name)+" "+d)
			if c.Primary {
				pk = append(pk, qident(c.Name))
			}
		}
		if len(pk) > 0 {
			defs = append(defs, "PRIMARY KEY ("+strings.Join(pk, ", ")+")")
		}
		ine := ""
		if in.IfNotExist {
			ine = "IF NOT EXISTS "
		}
		return "CREATE TABLE " + ine + qident(in.Schema, in.Table) + " (\n  " + strings.Join(defs, ",\n  ") + "\n)", nil
	}
	// Every other operation names an existing table.
	t, err := s.resolve(ctx, in.Schema, in.Table)
	if err != nil {
		return "", err
	}
	tbl := t.quoted
	word := map[string]string{"r": "TABLE", "p": "TABLE", "v": "VIEW", "m": "MATERIALIZED VIEW", "f": "FOREIGN TABLE"}[t.kind]
	isTable := t.kind == "r" || t.kind == "p"
	switch in.Op {
	case "rename_table":
		if err := checkName("new name", in.NewName); err != nil {
			return "", host.Invalid(err)
		}
		return "ALTER " + word + " " + tbl + " RENAME TO " + qident(in.NewName), nil
	case "set_schema":
		if err := checkName("schema", in.NewSchema); err != nil {
			return "", host.Invalid(err)
		}
		var ok bool
		if err := s.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = $1 AND nspname NOT LIKE 'pg\_%' AND nspname <> 'information_schema')`, in.NewSchema).Scan(&ok); err != nil {
			return "", err
		}
		if !ok {
			return "", actions.NotFound("There is no schema " + in.NewSchema + " in this database.")
		}
		return "ALTER " + word + " " + tbl + " SET SCHEMA " + qident(in.NewSchema), nil
	case "comment_table":
		lit := "NULL"
		if in.Comment != "" {
			if lit, err = quoteLiteral(in.Comment); err != nil {
				return "", host.Invalid(err)
			}
		}
		return "COMMENT ON " + word + " " + tbl + " IS " + lit, nil
	case "duplicate_table":
		if !isTable {
			return "", actions.InvalidParams("Only tables can be duplicated.")
		}
		if err := checkName("new name", in.NewName); err != nil {
			return "", host.Invalid(err)
		}
		dest := qident(in.Schema, in.NewName)
		// Structure copy keeps defaults, constraints, indexes and comments; the data is copied after it when asked.
		sql := "CREATE TABLE " + dest + " (LIKE " + tbl + " INCLUDING ALL)"
		if in.WithData {
			sql += stmtSep + "INSERT INTO " + dest + " SELECT * FROM " + tbl
		}
		return sql, nil
	case "add_column", "alter_column", "drop_column", "rename_column":
		return s.columnSQL(ctx, in, t, tbl, word, isTable)
	}
	return s.structureSQL(ctx, in, t, tbl, word, isTable)
}

// columnSQL handles the column operations (S4).
func (s *session) columnSQL(ctx context.Context, in AlterIn, t *tableInfo, tbl, word string, isTable bool) (string, error) {
	if !isTable {
		return "", actions.InvalidParams("Columns can only be changed on tables.")
	}
	has := func(n string) bool {
		for _, c := range t.columns {
			if c.Name == n {
				return true
			}
		}
		return false
	}
	switch in.Op {
	case "add_column":
		if in.Column == nil {
			return "", actions.InvalidParams("column: describe the new column.")
		}
		if err := checkName("column", in.Column.Name); err != nil {
			return "", host.Invalid(err)
		}
		if has(in.Column.Name) {
			return "", actions.Conflict("The table already has a column named " + in.Column.Name + ".")
		}
		d, err := in.Column.def(s.version)
		if err != nil {
			return "", actions.InvalidParams("column: " + err.Error())
		}
		return "ALTER TABLE " + tbl + " ADD COLUMN " + qident(in.Column.Name) + " " + d, nil
	case "drop_column":
		if !has(in.Name) {
			return "", actions.NotFound("There is no column " + in.Name + " in this table.")
		}
		if len(t.columns) == 1 {
			return "", actions.Conflict("A table needs at least one column; drop the table instead.")
		}
		c := ""
		if in.Cascade {
			c = " CASCADE"
		}
		return "ALTER TABLE " + tbl + " DROP COLUMN " + qident(in.Name) + c, nil
	case "rename_column":
		if !has(in.Name) {
			return "", actions.NotFound("There is no column " + in.Name + " in this table.")
		}
		if err := checkName("new name", in.NewName); err != nil {
			return "", host.Invalid(err)
		}
		return "ALTER TABLE " + tbl + " RENAME COLUMN " + qident(in.Name) + " TO " + qident(in.NewName), nil
	case "alter_column":
		if !has(in.Name) {
			return "", actions.NotFound("There is no column " + in.Name + " in this table.")
		}
		col := qident(in.Name)
		switch in.Extra.AlterWhat {
		case "type":
			ty, err := checkType(in.Extra.Value)
			if err != nil {
				return "", actions.InvalidParams("type: " + err.Error())
			}
			// USING col::type makes a conversion explicit; PostgreSQL refuses it when the values cannot convert.
			return "ALTER TABLE " + tbl + " ALTER COLUMN " + col + " TYPE " + ty + " USING " + col + "::" + ty, nil
		case "set_not_null":
			return "ALTER TABLE " + tbl + " ALTER COLUMN " + col + " SET NOT NULL", nil
		case "drop_not_null":
			return "ALTER TABLE " + tbl + " ALTER COLUMN " + col + " DROP NOT NULL", nil
		case "set_default":
			spec := ColumnSpec{Default: in.Extra.Value, DefaultFn: in.Extra.Kind == "function"}
			d, err := spec.defaultSQL()
			if err != nil {
				return "", actions.InvalidParams(err.Error())
			}
			return "ALTER TABLE " + tbl + " ALTER COLUMN " + col + " SET DEFAULT " + d, nil
		case "drop_default":
			return "ALTER TABLE " + tbl + " ALTER COLUMN " + col + " DROP DEFAULT", nil
		case "comment":
			lit := "NULL"
			if in.Extra.Value != "" {
				var err error
				if lit, err = quoteLiteral(in.Extra.Value); err != nil {
					return "", host.Invalid(err)
				}
			}
			return "COMMENT ON COLUMN " + tbl + "." + col + " IS " + lit, nil
		}
		return "", actions.InvalidParams("alter_what: type, set_not_null, drop_not_null, set_default, drop_default or comment.")
	}
	return "", actions.InvalidParams("op: unknown operation.")
}

func registerDDL(r *actions.Registry, env *host.Env) {
	r.Register(actions.Action{Name: "pg.table_alter", Mutating: true, Description: "Change a database's structure from structured input: create, rename, duplicate, comment or move a table; add, change, rename or drop a column. dry_run returns the SQL only.", Handler: func(ctx context.Context, p json.RawMessage) (any, error) {
		var in AlterIn
		if err := host.Decode(p, &in); err != nil {
			return nil, err
		}
		if err := in.check(); err != nil {
			return nil, err
		}
		var out map[string]any
		err := withOwner(ctx, env, in.Target, in.Database, func(s *session) error {
			sql, err := s.alterSQL(ctx, in)
			if err != nil {
				return err
			}
			out = map[string]any{"sql": strings.ReplaceAll(sql, stmtSep, ";\n")}
			if in.DryRun {
				return nil
			}
			// CREATE / DROP INDEX CONCURRENTLY and REINDEX CONCURRENTLY cannot run inside a transaction block.
			if in.Extra.Concurrent && (in.Op == "create_index" || in.Op == "drop_index" || in.Op == "reindex_index" || in.Op == "detach_partition") {
				if _, err := s.Exec(ctx, sql); err != nil {
					return userError(err)
				}
				return nil
			}
			// A duplicate with data is two statements; both run in one transaction so a failure leaves nothing behind.
			tx, err := s.Begin(ctx)
			if err != nil {
				return err
			}
			defer tx.Rollback(ctx)
			for _, stmt := range strings.Split(sql, stmtSep) {
				if _, err := tx.Exec(ctx, stmt); err != nil {
					return userError(err)
				}
			}
			return tx.Commit(ctx)
		})
		return out, err
	}})
}
