<?php

declare(strict_types=1);

namespace NimVor\Tests\Unit;

use PHPUnit\Framework\TestCase;
use NimVor\Security\QrCode;

/**
 * Fixtures were produced by an independent encoder (python-qrcode, level M,
 * byte mode, same mask) and must match module for module.
 */
final class QrCodeTest extends TestCase
{
    private static function rows(QrCode $q): array
    {
        $out = [];
        for ($y = 0; $y < $q->size(); $y++) {
            $r = '';
            for ($x = 0; $x < $q->size(); $x++) {
                $r .= $q->dark($y, $x) ? '1' : '0';
            }
            $out[] = $r;
        }
        return $out;
    }

    public function testMatchesReferenceVersion1(): void
    {
        $q = QrCode::encode('NimVor', 3);
        self::assertSame(1, $q->version);
        self::assertSame([
            '111111101011001111111',
            '100000101110001000001',
            '101110100100001011101',
            '101110101011001011101',
            '101110100010001011101',
            '100000100010001000001',
            '111111101010101111111',
            '000000001010000000000',
            '101101110000001001011',
            '100111000100100100001',
            '011100110010111110011',
            '110101000010110001011',
            '100110110111010010011',
            '000000001110010000101',
            '111111101100011011000',
            '100000101101111111101',
            '101110100001001000011',
            '101110101100010101010',
            '101110101111010000000',
            '100000100111101110001',
            '111111101111100100100',
        ], self::rows($q));
    }

